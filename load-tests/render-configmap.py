#!/usr/bin/env python3
"""Render the k6 scripts as a ConfigMap, without needing kubectl.

The load-test scripts live in this directory and are the single source of truth.
The homelab repository mounts them into the k6 CronJob from a ConfigMap, so this
script produces that ConfigMap and writes it into the homelab checkout. The
CronJob remaps the flattened keys back into lib/ so the relative imports resolve.

Usage:
    ./render-configmap.py > /path/to/golias-homelab/apps/wealth-loadtest/scripts-configmap.yaml

Requires only the standard library. ConfigMap keys must match
[-._a-zA-Z0-9]+, so lib/api.js is stored as api.js and the CronJob's
volume items map it back to lib/api.js on disk.
"""

import sys
from pathlib import Path

# (ConfigMap key, path relative to this script)
FILES = [
    ("wealth-service.js", "wealth-service.js"),
    ("config.js", "lib/config.js"),
    ("api.js", "lib/api.js"),
    ("workload.js", "lib/workload.js"),
    ("uuid.js", "lib/uuid.js"),
]

NAME = "wealth-loadtest-scripts"
NAMESPACE = "wealth-loadtest"

INDENT = "    "


def fail(message):
    sys.exit(f"error: {message}")


def check_round_trip(path, content):
    """Refuse to emit content that would not survive YAML parsing.

    A literal block scalar cannot represent some byte sequences: a line with
    trailing whitespace, a tab used for indentation, or a line shorter than the
    block indent. Silently corrupting a script here would show up much later as
    a confusing k6 parse error, so catch it now.
    """
    for number, line in enumerate(content.split("\n"), start=1):
        if line != line.rstrip():
            fail(f"{path}:{number} has trailing whitespace, cannot be a YAML block scalar")
        if "\t" in line:
            fail(f"{path}:{number} contains a tab, which YAML will not indent predictably")
    if content.endswith("\n\n"):
        fail(f"{path} ends with a blank line, which a literal block scalar cannot preserve")


def render_block(key, content):
    # "|" keeps a single trailing newline, "|-" strips it. Matching the source
    # exactly means the mounted file is byte-identical to the one in git.
    style = "|" if content.endswith("\n") else "|-"
    body = "".join(INDENT + line + "\n" for line in content.split("\n"))
    # A "|-" block still emits a final newline after the last line, but the
    # parser discards it, so the value round-trips to the original bytes.
    return f"  {key}: {style}\n{body}"


def main():
    here = Path(__file__).resolve().parent

    blocks = []
    for key, relative in FILES:
        path = here / relative
        if not path.is_file():
            fail(f"missing {relative}")

        raw = path.read_bytes()
        try:
            content = raw.decode("utf-8")
        except UnicodeDecodeError as error:
            fail(f"{relative} is not valid UTF-8: {error}")

        check_round_trip(relative, content)
        blocks.append(render_block(key, content))

    total = sum(len((here / relative).read_bytes()) for _, relative in FILES)
    if total > 1024 * 1024:
        fail(f"scripts total {total} bytes, over the 1MiB ConfigMap limit")

    print("# Generated by wealth-service/load-tests/render-configmap.py")
    print("# Do not edit by hand: rerun the script and commit the result.")
    print("apiVersion: v1")
    print("kind: ConfigMap")
    print("metadata:")
    print(f"  name: {NAME}")
    print(f"  namespace: {NAMESPACE}")
    print("data:")
    print("\n".join(blocks), end="")
    print(f"# {total} bytes of script source")


if __name__ == "__main__":
    main()